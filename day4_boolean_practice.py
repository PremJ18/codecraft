
# Day 4 - Boolean and Negation Practice

is_student = True
is_working = False

print("Is student:", is_student)
print("Is working:", is_working)

print("\n--- Negation ---")
print("not True:", not True)
print("not False:", not False)

print("\n--- Comparisons ---")
print("5 > 2:", 5 > 2)
print("3 == 3:", 3 == 3)

print("\n--- Negation with Comparisons ---")
print("not (5 > 2):", not (5 > 2))
print("not (3 == 3):", not (3 == 3))
